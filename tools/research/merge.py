"""Turn the research in tools/research/<region>/ into the model's data modules.

  python3 tools/research/merge.py      → packages/model/{intl,species-intl,ports-intl,areas-intl}.js

Each region folder holds areas, ports, seasons, new species and rules (with sources);
see the BRIEF in git history. Protected areas live in packages/model/data/protected-areas-<d>.json.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES, OUT = ROOT / 'tools/research', ROOT / 'packages/model'
DATA = {  # data region → ocean, names, box (fixed: the grids are built for these boxes)
    'uspac': ('pac', 'California', 'California', {'w': -125.0, 'e': -117.0, 's': 32.3, 'n': 38.6}),
    'usgulf': ('atl', 'US Gulf & Florida', 'Golfo de EE. UU. y Florida', {'w': -97.9, 'e': -79.0, 's': 24.2, 'n': 30.8}),
    'caribe': ('atl', 'Northern Caribbean', 'Caribe norte', {'w': -85.2, 'e': -64.2, 's': 17.4, 'n': 27.4}),
}
# Time zone of each season region (closures switch at local midnight).
TZ = {'us-socal': 'America/Los_Angeles', 'us-central': 'America/Los_Angeles', 'us-norcal': 'America/Los_Angeles',
      'us-gulf-tx': 'America/Chicago', 'us-gulf-north': 'America/Chicago', 'us-gulf-fl': 'America/New_York',
      'us-fl-south': 'America/New_York', 'us-fl-east': 'America/New_York',
      'bahamas': 'America/Nassau', 'cuba': 'America/Havana', 'carib-west': 'America/Jamaica', 'carib-east': 'America/Puerto_Rico'}
BIG = {'uspac': {'k': 'uspac-all', 'd': 'uspac', 'r': 'us-socal', 'j': 'us-ca', 'big': True, 'en': 'All of California', 'es': 'Toda California',
                 'box': DATA['uspac'][3]}}
js = lambda x: json.dumps(x, ensure_ascii=False)

regions, seasons, juris, limits, closures, info, species, ports, areas = {}, {}, {}, {}, [], {}, {}, [], []
area_r = {}
for d, (ocean, en, es, box) in DATA.items():
    f = RES / d
    A = json.loads((f / 'areas.json').read_text())
    if not any(a.get('big') for a in A): A.append(BIG[d])
    for a in A:
        a = {k: a[k] for k in ('k', 'd', 'r', 'j', 'big', 'en', 'es', 'box') if a.get(k) is not None}
        if a.get('big') and not a.get('j'): a['j'] = None
        areas.append(a); area_r[a['k']] = a['r']; regions.setdefault(a['r'], {'ocean': ocean})
    for p in json.loads((f / 'ports.json').read_text()):
        ports.append({'name': p['name'], 'lat': p['lat'], 'lon': p['lon'], 'region': d})
    S = json.loads((f / 'seasons.json').read_text()); S.pop('_sources', None)
    for k, byR in S.items():
        for r, v in (byR or {}).items():
            if r in regions or r in TZ: seasons.setdefault(k, {})[r] = v
    R = json.loads((f / 'rules.json').read_text())
    juris.update(R['juris']); 
    for j, m in R['limits'].items(): limits.setdefault(j, {}).update(m)
    for c in R['closures']:
        rs = c.get('regions') or [area_r[a] for a in c.get('areas', []) if a in area_r]
        c = {**c, 'tz': TZ.get(rs[0], 'America/New_York') if rs else 'America/New_York', 'region': d}
        closures.append(c)
    for x in json.loads((f / 'new-species.json').read_text()):
        i = x.get('info') or {k: x[k] for k in ('spawn', 'conf', 'src', 'limit', 'beta') if k in x}
        sp = {k: x[k] for k in ('k', 'g', 'en', 'es', 'temp', 'depth', 'chl')}
        sp['season'] = [0] * 12
        if x['k'] in species:  # defined by two regions (yellowtail snapper): keep the first profile, merge sources
            info[x['k']]['src'] = info[x['k']].get('src', []) + [s for s in i.get('src', []) if s not in info[x['k']].get('src', [])]
            continue
        species[x['k']] = sp
        info[x['k']] = {'spawn': i.get('spawn'), 'conf': i.get('conf', 'low'), 'limit': 'general', 'beta': True, 'src': i.get('src', []), 'ocean': ocean}

hdr = '// GENERATED by tools/research/merge.py from tools/research/<region>/*.json — edit those, not this file.\n'
(OUT / 'intl.js').write_text(hdr + f'''// US waters and the northern Caribbean (phase 1: California, US Gulf + Florida, Bahamas /
// Greater Antilles / Puerto Rico / Virgin Islands). Every rule cites an official source (src/source).
// Season regions here are STRICT: a species without a local calendar is not mapped.
// Closures with cr: true are catch-and-release only: zones stay on the map, keeping is not allowed.

/** Season regions: ocean. */
export const INTL_REGIONS = {js(regions)};
/** {{ species: {{ seasonRegion: '012233332100' | null }} }} */
export const INTL_SEASONS = {js(seasons)};
/** Jurisdictions other than Mexico. */
export const JURIS = {js(juris)};
/** Limits per jurisdiction and species (_general = the general bag limit). */
export const INTL_LIMITS = {js(limits)};
/** Closed seasons (no retention), or catch-and-release only (cr). */
export const INTL_CLOSURES = {js(closures)};
/** Info for the species added for these waters. */
export const INTL_INFO = {js({k: {kk: vv for kk, vv in v.items() if kk != 'ocean'} for k, v in info.items()})};
/** Ocean of the species added for these waters. */
export const INTL_OCEAN = {js({k: v['ocean'] for k, v in info.items()})};
''')
(OUT / 'species-intl.js').write_text(hdr + '// Species added for US waters and the Caribbean. LOW-CONFIDENCE profiles (sources in intl.js INTL_INFO).\n'
    '// season = Los Cabos calendar (all 0: not found there); the regional calendars decide where they show.\n'
    f'export const INTL_SPECIES = {js(list(species.values()))};\n')
(OUT / 'ports-intl.js').write_text(hdr + f'export const INTL_PORTS = {js(ports)};\n')
(OUT / 'areas-intl.js').write_text(hdr + f'''export const INTL_DATA_REGIONS = {js([{'k': d, 'ocean': o, 'en': en, 'es': es, 'box': b} for d, (o, en, es, b) in DATA.items()])};
/** Map areas (chips). j = jurisdiction (rules, licence, never-keep list). */
export const INTL_AREAS = {js(areas)};
''')
print(len(areas), 'areas,', len(ports), 'ports,', len(species), 'species,', len(closures), 'closures,', len(juris), 'jurisdictions,', len(regions), 'season regions')
